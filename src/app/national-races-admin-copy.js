// Les variables des modèles ({prenom}…) s'affichent telles quelles : on ne
// remplace que les clés fournies.
function fill(text, values = {}) {
  return Object.entries(values).reduce((result, [key, value]) => result.split(`{${key}}`).join(value ?? ""), String(text || ""));
}

function useNationalRacesAdminCopy() {
  const { language } = useLanguage();
  const copy = NATIONAL_RACES_ADMIN_COPY[language] || NATIONAL_RACES_ADMIN_COPY.en;
  return { copy, fill, raceLabel: (code, fallback = "") => copy.raceLabels[code] || fallback };
}

export { NATIONAL_RACES_ADMIN_COPY, useNationalRacesAdminCopy };
