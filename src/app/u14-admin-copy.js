function fill(text, values = {}) {
  return Object.entries(values).reduce((result, [key, value]) => result.split(`{${key}}`).join(value ?? ""), String(text || ""));
}

// Nom de course (« U14 Filles - 60 m ») dans la langue de l'interface.
function translateU14RaceLabelFor(label, language) {
  const text = String(label || "");
  return language === "en" ? text.replace(/Filles/g, "Girls").replace(/Garçons/g, "Boys") : text;
}

function useU14AdminCopy() {
  const { language } = useLanguage();
  const copy = U14_ADMIN_COPY[language] || U14_ADMIN_COPY.en;
  return { copy, language, fill, raceLabel: (label) => translateU14RaceLabelFor(label, language) };
}

export { U14_ADMIN_COPY, fill as fillU14Copy, translateU14RaceLabelFor, useU14AdminCopy };
